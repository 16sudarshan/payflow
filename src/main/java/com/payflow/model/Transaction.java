package com.payflow.model;
import java.util.UUID;

import com.payflow.model.enums.CardType;
import com.payflow.model.enums.TransactionStatus;
import com.payflow.model.enums.TransactionType;
import java.time.LocalDateTime;

public class Transaction {

    // Transaction Identity
    private String transactionId;      // Unique ID we generate
    private String stan;               // System Trace Audit Number
    private String rrn;                // Retrieval Reference Number

    // Card Details (from your answer!)
    private String maskedCardNumber;   // Never store real card number!
    private CardType cardType;         // VISA, MASTERCARD etc
    private String expiryMonth;        // From card
    private String expiryYear;         // From card

    // Transaction Details
    private double amount;             // Payment amount
    private String currency;           // USD, EUR, INR
    private TransactionType type;      // PURCHASE, REFUND, REVERSAL
    private TransactionStatus status;  // APPROVED, DECLINED etc

    // Merchant Details (from your answer!)
    private String merchantId;         // Merchant unique ID
    private String merchantName;       // Shop name
    private String terminalId;         // Terminal where swiped

    // Response Details
    private String authorizationCode;  // If approved: "AUTH123"
    private String responseCode;       // "00"=Approved "51"=Insuff funds
    private String declineReason;      // If declined: reason

    // Timing
    private LocalDateTime timestamp;

    public Transaction(String maskedCardNumber,
                       CardType cardType,
                       String expiryMonth,
                       String expiryYear,
                       double amount,
                       String currency,
                       TransactionType type,
                       String stan,
                       String merchantId,
                       String merchantName,
                       String terminalId) {

        // Auto generated by system
        this.transactionId = UUID.randomUUID().toString();
        this.timestamp     = LocalDateTime.now();
        this.status        = TransactionStatus.PENDING;

        // From parameters
        this.maskedCardNumber = maskedCardNumber;
        this.cardType         = cardType;
        this.expiryMonth      = expiryMonth;
        this.expiryYear       = expiryYear;
        this.amount           = amount;
        this.currency         = currency;
        this.type             = type;
        this.stan             = stan;
        this.merchantId       = merchantId;
        this.merchantName     = merchantName;
        this.terminalId       = terminalId;
    }

    public String getTransactionId() {
        return transactionId;
    }

    public void setTransactionId(String transactionId) {
        this.transactionId = transactionId;
    }

    public String getStan() {
        return stan;
    }

    public void setStan(String stan) {
        this.stan = stan;
    }

    public String getRrn() {
        return rrn;
    }

    public void setRrn(String rrn) {
        this.rrn = rrn;
    }

    public String getMaskedCardNumber() {
        return maskedCardNumber;
    }

    public void setMaskedCardNumber(String maskedCardNumber) {
        this.maskedCardNumber = maskedCardNumber;
    }

    public CardType getCardType() {
        return cardType;
    }

    public void setCardType(CardType cardType) {
        this.cardType = cardType;
    }

    public String getExpiryMonth() {
        return expiryMonth;
    }

    public void setExpiryMonth(String expiryMonth) {
        this.expiryMonth = expiryMonth;
    }

    public String getExpiryYear() {
        return expiryYear;
    }

    public void setExpiryYear(String expiryYear) {
        this.expiryYear = expiryYear;
    }

    public double getAmount() {
        return amount;
    }

    public void setAmount(double amount) {
        this.amount = amount;
    }

    public String getCurrency() {
        return currency;
    }

    public void setCurrency(String currency) {
        this.currency = currency;
    }

    public TransactionType getType() {
        return type;
    }

    public void setType(TransactionType type) {
        this.type = type;
    }

    public TransactionStatus getStatus() {
        return status;
    }

    public void setStatus(TransactionStatus status) {
        this.status = status;
    }

    public String getMerchantId() {
        return merchantId;
    }

    public void setMerchantId(String merchantId) {
        this.merchantId = merchantId;
    }

    public String getMerchantName() {
        return merchantName;
    }

    public void setMerchantName(String merchantName) {
        this.merchantName = merchantName;
    }

    public String getTerminalId() {
        return terminalId;
    }

    public void setTerminalId(String terminalId) {
        this.terminalId = terminalId;
    }

    public String getAuthorizationCode() {
        return authorizationCode;
    }

    public void setAuthorizationCode(String authorizationCode) {
        this.authorizationCode = authorizationCode;
    }

    public String getResponseCode() {
        return responseCode;
    }

    public void setResponseCode(String responseCode) {
        this.responseCode = responseCode;
    }

    public String getDeclineReason() {
        return declineReason;
    }

    public void setDeclineReason(String declineReason) {
        this.declineReason = declineReason;
    }

    public LocalDateTime getTimestamp() {
        return timestamp;
    }

    public void setTimestamp(LocalDateTime timestamp) {
        this.timestamp = timestamp;
    }


    @Override
    public String toString() {
        return "Transaction{" +
                "id="          + transactionId +
                ", card="      + maskedCardNumber +
                ", type="      + type +
                ", amount="    + amount +
                ", currency="  + currency +
                ", status="    + status +
                ", merchant="  + merchantName +
                ", stan="      + stan +
                ", time="      + timestamp +
                "}";
    }



}

